/**
 * 接続先に応じた TLS の設定を返す。
 * - Supabase(*.supabase.com / *.supabase.co): Supabase の認証局で証明書を検証して暗号化する
 * - それ以外(ローカルの docker-compose など): TLS を使わない(undefined)
 *
 * 接続文字列に sslmode を書くと pg がこの設定を上書きするため、本番の DATABASE_URL には sslmode を付けない。
 */
export function sslOptionsFor(connectionString: string): ConnectionOptions | undefined {
  let host: string;
  try {
    host = new URL(connectionString).hostname;
  } catch {
    return undefined;
  }
  if (host.endsWith(".supabase.com") || host.endsWith(".supabase.co")) {
    return { ca: SUPABASE_ROOT_CA_2021, rejectUnauthorized: true };
  }
  return undefined;
}
